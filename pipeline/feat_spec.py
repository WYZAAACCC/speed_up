#!/usr/bin/env python3
"""
逐面神经算子的特征定义 —— **单一来源**。

train_rollout_batched.py（数据侧与 rollout 侧两处）和 replay_transfer.py
都必须从这里取特征顺序。原因：这三处的张量形状都是 N_FEAT，
**顺序错了 assert 拦不住**，只会静默地把语义搞乱（训练时 X 的含义
和回放时不同），属于最难查的一类 bug。

改特征只需改这个文件。

=============================================================================
特征顺序（N_FEAT = 26）
=============================================================================
  0-2   面: area, area_over_Ai, area_over_Aj        静态几何
  3     面: 溶质过量（状态量）
  4-6   晶粒 i: volume, n_faces, shape_factor
  7     晶粒 i: c_bulk
  8-10  晶粒 j: 同上
  11    晶粒 j: c_bulk
  12    步长 dt
  13    体积对比 (vi-vj)/(vi+vj)
  14    配位数对比 n_faces_i - n_faces_j
  15    浓度对比 (ci-cj)/(|ci|+|cj|)
  ---- 2026-09-17 新增（第二档 / 物理量）----
  16    面: T_avg
  17    晶粒 i: T_avg
  18    晶粒 j: T_avg
  19    面: dtheta_deg（取向差）
  20    面: align_i（晶粒 i 易生长轴与热梯度的四重对齐度）
  21    面: align_j
  22-23 晶粒 i: cos(4θ), sin(4θ)
  24-25 晶粒 j: cos(4θ), sin(4θ)

=============================================================================
【为什么温度是必加的 —— 不是"锦上添花"，是缺了原理上算不对】
=============================================================================
晶界迁移率 L = 4/3 * M0 * exp(-Q/(kb*T)) / wGB，Ti64 的 Q = 3.234 eV。
实测同一时刻、同处**固相**内的两个晶粒：
    T = 992 K  ->  exp(-Q/kbT) = 2.6e-9
    T = 373 K  ->  exp(-Q/kbT) ~ 1e-36
**迁移率差 27 个数量级。**
原来的 16 维特征里完全没有温度，于是几何相同、成分相同的两条晶面，
一条在熔池后方（冻结）、一条在糊状区（活跃），算子**无法区分**，
只能学一个平均值。

温度的另一层作用：它是编码"相对激光的位置"的**正确**方式 ——
不用把扫描路径硬编码进特征（加 cen_x/cen_y 是错的做法，那会让算子
只对这一条具体路径有效）。

注意 [数据来源]：T_avg 是**已知输入**（温度场是给定的），不是算子要预测的量。
所以训练时读真值、回放时也读真值，两者一致，没有信息泄漏。

=============================================================================
【为什么 dtheta / align 是"取向的充分统计量"】
=============================================================================
这是可以严格论证的：模型里的 kappa_op / gamma_asymm / L 对晶体取向的依赖
**只**通过下面两条通道进入：
  * 逐对取向差 dtheta_ij  —— 2a，Read-Shockley 因子由它决定
  * 逐晶粒易生长轴与热梯度的对齐度 align —— 2b
所以严格来说 cos(4θ)/sin(4θ) 是**冗余**的，保留它们是因为：
  (a) 明确要求把取向作为输入；
  (b) 以后若换用其它取向依赖模型，数据不必重做。

用 cos(4θ)/sin(4θ) 而不是 θ 本身：β-Ti 的 <100> 在 2D 是**四重对称**，
θ 与 θ+90 是同一个取向，所以周期是 90°。4θ 的 cos/sin 周期正是 90°
（cos(4(θ+90)) = cos(4θ+360) = cos(4θ)），而直接给 θ 会在 0/90 处
产生一个人为的断崖（89.9° 与 0.1° 物理上几乎相同，特征空间里却相距最远）。

=============================================================================
【缺失值处理】
=============================================================================
C 版算例不输出第二档变量，extract.py 会把这些列写成 NaN。
读取端统一：标准化用 nanmean/nanstd，缺失值填该列均值
（标准化后恰为 0，即"无信息"），不会污染其余特征。
"""

import math

FSTAT = ["area", "area_over_Ai", "area_over_Aj"]

N_TIER2 = 10
N_FEAT = 16 + N_TIER2          # = 26


def _num(d, key):
    """从记录里取一个有限的浮点数；缺失/NaN 一律返回 NaN。"""
    try:
        v = float(d.get(key, "nan"))
    except (TypeError, ValueError):
        return float("nan")
    return v if math.isfinite(v) else float("nan")


def _cos4(theta_deg):
    return math.cos(math.radians(4.0 * theta_deg)) if math.isfinite(theta_deg) else float("nan")


def _sin4(theta_deg):
    return math.sin(math.radians(4.0 * theta_deg)) if math.isfinite(theta_deg) else float("nan")


def tier2_features(r, a, b):
    """第二档 10 个特征，顺序见模块 docstring 的 16-25。

    r —— 该面的记录（faces.csv 的一行）
    a —— 晶粒 i 的记录（grains.csv 的一行）
    b —— 晶粒 j 的记录
    """
    ti, tj = _num(a, "theta_deg"), _num(b, "theta_deg")
    return [
        _num(r, "T_avg"),         # 16 面温度
        _num(a, "T_avg"),         # 17 晶粒 i 温度
        _num(b, "T_avg"),         # 18 晶粒 j 温度
        _num(r, "dtheta_deg"),    # 19 取向差
        _num(r, "align_i"),       # 20
        _num(r, "align_j"),       # 21
        _cos4(ti), _sin4(ti),     # 22-23
        _cos4(tj), _sin4(tj),     # 24-25
    ]
