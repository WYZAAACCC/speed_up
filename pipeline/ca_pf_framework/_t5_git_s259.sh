## ★ 判别实验方案（**单变量，按优先级**）
### 实验 B1：**单块**（`B=1`）—— 判"多块相互作用"是不是必要条件
* **配置**：`--B 1`，其余同 `t5N276`（N=80 · nvar 12 · m 23 ⇒ nv=276 · eng-elong 7）
* **判据**：**终态长宽比**。若 **仍崩到 ~1.2** ⇒ **多块不是原因**（B1 排除）;
  若**保持 ≥5** ⇒ **多块相互作用是原因**。
* **成本**：与主算例同级（~4 小时，内存 ~5.7 GB）。

### 实验 B2：**单变体单块**（`nvar 1 --m 23 --B 1`）—— 判"同变体密集堆叠"是不是原因
* **配置**：只有 1 个变体（nv=23）⇒ **所有板条同变体**，但**数量少**（最多 23 根）
* **判据**：若宽比**保持** ⇒ 说明是"**同变体场太多**"（密集堆叠）导致;
  若**仍崩** ⇒ 与同变体堆叠无关，指向**单根自身**的演化。

### 实验 B3：**单根**（`--B 1 --m 1 --nvar 1` ⇒ nv=1）—— 判"单根是否自身退化"
* **配置**：**只有 1 个场** ⇒ 无邻居、无竞争、无堆叠
* **判据**：**最干净的二选一** ——
  * **保持扁（宽比 ≥5）** ⇒ 退化**必须**由多体相互作用引起 ⇒ B1/B2 的结果可定位到具体机制;
  * **自身变钝** ⇒ **单根的动力学有问题** ⇒ 要查迁移率各向异性/重初始化/曲率驱动。

### 实验 B4：**关掉 `--grow-stack`**（用纯 `fresh` 形核）—— 判"邻位形核"是否参与
* **配置**：`--nuc-init 6` 但**不传** `--grow-stack`（⇒ 只有 fresh）
* **判据**：若退化**显著减轻** ⇒ `attach`/`stack` 的**邻位播种几何**是原因
  （它们把种子贴着旧板条放 ⇒ 新核长在"被包住"的环境里）。

