# -*- coding: utf-8 -*-
"""_r1_facetfeas.py --- ★ A-3 的**可行性判决**：把界面能各向异性加强到多少才能造出面？

问题
----
A-3 的结论是"边缘圆化，因为 **`M(n)` 控制速率、不能造面**，而界面能通道只占驱动 0.1%"。
那么自然要问：**把 `aniso`（`γ+γ_θθ` 的各向异性强度）加大，能不能把面造出来？**

判据（先写死）
--------------
  F-1 曲率项与化学驱动的**量级比** `|stk·κ| / Δf`。
      只有当它接近或超过 1 时，界面能才可能支配**形状**。
      （本引擎里 γ 只以 `−stk·κ` 进入 `dG`，见 `windowB_surface.advance` 的 `dG_cell`。）
  F-2 使 `γ+γ_θθ < 0` 所需的 `aniso`（**缺失取向**、即 Wulff 造面的经典条件）：
      `herring_stiffness` 给 `γ+γ_θθ = γ0·(1 + 2Λ − 3Λ·sin²θ)`，
      在 `sin²θ = 1`（法向 ⊥ n*）处为 `γ0·(1 − Λ)` ⇒ **Λ > 1 才会变负**。
  F-3 用**真实几何**（板条 κ、γ0、Δf）算出一个数量级结论。

⚠ 本脚本**不跑仿真**，只做量级判决 —— 目的是决定"要不要花机时试 `aniso>1`"。
"""
import numpy as np

# ---- 本项目的真实参数（R24 标准域上的实测/设定值）----
GAMMA0 = 0.15          # J/m²  界面能（引擎 `gamma=0.15`）
DF = 3.5e8             # J/m³  化学驱动（T16 的 DF）
THICK = 0.4e-6         # m     板条厚度尺度（尖端的曲率半径 ≈ T/2）
KAPPA_TIP = 2.0 / THICK        # m^-1  凸尖端 κ ≈ 2/R
KAPPA_FACE = 1.0 / (5e-6)      # m^-1  宽面（面内半径 ~5 µm）

print('=' * 92)
print('A-3 可行性判决：加强界面能各向异性能不能造出面？')
print('=' * 92)
print('参数：γ0 = %.2f J/m² ；Δf = %.3g J/m³ ；板厚 ~%.2f µm' % (GAMMA0, DF, THICK * 1e6))
print('      κ_尖端 ≈ 2/R = %.2e m⁻¹ ；κ_宽面 ≈ %.2e m⁻¹' % (KAPPA_TIP, KAPPA_FACE))

print('\n【F-1/F-3】`|stk·κ| / Δf` 随 aniso 的变化（`herring_stiffness`, herring=True）')
print('   γ+γ_θθ = γ0·(1 + 2Λ − 3Λ·sin²θ)')
print('  %6s | %12s %12s | %12s %12s | %10s' %
      ('Λ', 'stk(θ=0)', 'stk(θ=90°)', '比(宽面)', '比(尖端)', 'θ=90°符号'))
for Lam in (0.4, 1.0, 1.5, 2.0, 5.0, 10.0, 30.0):
    s0 = GAMMA0 * (1 + 2 * Lam)              # sin²θ = 0
    s90 = GAMMA0 * (1 - Lam)                 # sin²θ = 1
    # 宽面用 stk(θ=0)；尖端取 |stk(θ=90°)|（那里法向最接近 a）
    r_face = abs(s0 * KAPPA_FACE) / DF
    r_tip = abs(s90 * KAPPA_TIP) / DF
    print('  %6.1f | %12.4g %12.4g | %11.3e %11.3e | %10s'
          % (Lam, s0, s90, r_face, r_tip, '负' if s90 < 0 else '正'))

print('\n【F-2】缺失取向（Wulff 造面）条件：Λ > 1 时 stk(θ=90°) < 0')
print('   ⇒ 但要**影响形状**，还需要 F-1 的比值够大（接近或超过 1）。')
print('   ⇒ 上表最后一列显示：即使 Λ=30，比值也只有 ~1e-2 量级。')

need = DF / KAPPA_TIP / GAMMA0
print('\n【数量级结论】要让**尖端**的曲率项与 Δf 同量级，需要 `stk_tip ≈ Δf/κ_tip = %.3g J/m²`'
      % (DF / KAPPA_TIP))
print('   ⇒ 即 `γ0·|1−Λ| ≈ %.3g` ⇒ **Λ ≈ %.3g**（或 γ0 本身放大 %.3g 倍）'
      % (DF / KAPPA_TIP, DF / KAPPA_TIP / GAMMA0, DF / KAPPA_TIP / GAMMA0))
print('   而 γ0 = %.2f J/m² 是 Ti64 马氏体界面的**物理值**（放大它就不是这个材料了）。' % GAMMA0)

print('\n' + '=' * 92)
print('★ 判决：**加强 `aniso` 造不出面。**')
print('  理由：本引擎里界面能只以 `−stk·κ` 进入驱动，`κ ~ 1/(0.1–1 µm) ~ 1e6 m⁻¹`，')
print('        而 `Δf ~ 3.5e8 J/m³` ⇒ 即使把 Λ 加到 30（γ+γ_θθ 在 θ=90° 变负、')
print('        已满足"缺失取向"的经典条件），比值仍只有 ~1e-2。')
print('        ⇒ **不需要浪费机时去扫 `aniso > 1`。**（这条把 D 类"已否决的路"再加一条。）')
print('★ 要拿到平边缘，只能**新增机制**（见 A-3 的修法选项），不是调参：')
print('   (a) 让**迁移率**依赖局部**失配应变**（边缘处失配最集中 ⇒ 局部钉扎）；')
print('   (b) 换**界面表示**（显式刻面 / 强各向异性 Wulff 型界面），代价是另一套数值。')
print('=' * 92)
