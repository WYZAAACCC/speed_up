#!/usr/bin/env python3
"""_r460_feasibility.py —— 任务(4)的**可行性算术**（供审阅，先不动手）

用户新任务的关键约束：
  * 盒子放大到 **≥10 µm**
  * **随机形核**，让板条与块**占满整个盒子**
  * 按**真实物理**（不用常数驱动力）
  * 同时关注：单根生长 / 堆叠成块 / 块间相互影响

本脚本只回答三个"能不能"：
  **A. 填满 10 µm 盒子需要多少根板条？**
  **B. 那么多根板条，C-3（顺序形核）要多少步？**
  **C. 那么多场，内存够不够？**
"""
import sys

import numpy as np

sys.path.insert(0, '.')
import windowB_closure as CL      # noqa: E402
from windowB_km import T0_TI64, M_S_TI64   # noqa: E402

P = print
P('=' * 100)
P('_r460 —— 任务(4)的可行性算术')
P('=' * 100)

DX = 62.5e-9
CFL = CL.CFL_DEFAULT
T_F = 298.0

# ---------------------------------------------------------------- A 需要多少根
P('\n[A] **填满 10 µm 盒子需要多少根板条？**')
P('    %-34s %-14s %-16s %s' % ('单根几何', '单根体积', '填满 1000 µm³ 需要', '备注'))
CASES = [
    ('当前播种 1000×500×510 nm', 1000e-9 * 500e-9 * 510e-9, ''),
    ('长到 2× 长（2000 nm）', 2000e-9 * 500e-9 * 510e-9, ''),
    ('长到 4× 长（4000 nm）', 4000e-9 * 500e-9 * 510e-9, ''),
    ('**物理尺寸** 8 µm×0.9 µm×0.5 µm', 8e-6 * 0.9e-6 * 0.5e-6, '实测 Ti-64 板条'),
]
for name, v, note in CASES:
    need = 1000e-18 / v            # 10 µm 盒 = 1000 µm³ = 1000e-18 m³
    P('    %-34s %-14.3f %-16.0f %s' % (name, v * 1e18, need, note))

# ---------------------------------------------------------------- B C-3 步数
P('\n[B] **C-3（顺序形核）要多少步？**（`steps_min_ordered`，与 MOB/q 无关）')
P('    框架闭式：`N_steps ≥ ΔT·[(T0−T_start)+ΔT/2]·α_KM·L_lath/(cfl·dx·(T0−T_start))`')
P('    而 `n = α_KM·ΔT` ⇒ **`N_steps ∝ n · L_lath`**')
P('')
P('    %-16s %-14s %-18s %-16s %s'
  % ('目标根数 n', 'L_lath (nm)', '需要的 ΔT (K)', 'T_f 需要 (K)', 'steps_min'))
V_TARGETS = [(23, 1000e-9), (64, 1000e-9), (280, 1000e-9), (280, 8000e-9)]
#   对每个 (n, L) 反解 α 使 n = α·(Ms − 298) ⇒ α = n/(Ms−298)；再算 step
for n, L in V_TARGETS:
    alpha = n / (M_S_TI64 - T_F)
    st = CL.steps_min_ordered(alpha, L_lath=L, dx=DX, cfl=CFL, T_f=T_F)
    P('    %-16d %-14.0f %-18s %-16s **%.0f**'
      % (n, L * 1e9, '%.0f' % (M_S_TI64 - T_F), '%.0f' % T_F, st))
    P('        （α_KM 需 = %.4f /K；按 6 s/步 ≈ **%.0f 小时**）'
      % (alpha, st * 6 / 3600))

# ---------------------------------------------------------------- C 内存
P('\n[C] **内存够不够？**（`phi` 是 `(nreg, N³)`，这是**不可避**的那一块）')
P('    %-6s %-12s %-12s %-14s %-14s %s'
  % ('N', '盒(µm)', 'N³', 'nreg=280 f64', 'nreg=280 f32', 'nreg=119 f64'))
for N in (112, 128, 160):
    N3 = N ** 3
    P('    %-6d %-12.1f %-12.3e %-14.2f %-14.2f %s'
      % (N, N * DX * 1e6, N3,
         280 * N3 * 8 / 2**30, 280 * N3 * 4 / 2**30,
         119 * N3 * 8 / 2**30))
P('    ⚠ 还要加上：`argmin` 的临时量（同量级）、FFT 工作区、测量。')
P('    ⚠ **本机 WSL 预算 = 22 GB**（`AGENTS.md §1.3`）。')
P('')
P('    ★ 好消息：引擎的**每步热路径**走 `elastic_driving_pair`（只算 winner/runner-up）')
P('      ⇒ 每步的 `ed` 是 **O(N³)** 而不是 `O(nreg·N³)`。')
P('      但 `region()`（每一步多次）与 `sussman_reinit` 仍要遍历整个 `phi`。')

P('\n' + '=' * 100)
P('[结论]')
P('  1. 要"填满 10 µm 盒子"，板条必须长到**接近物理尺寸**，否则需要上千根；')
P('  2. 而**根数 × 板条长**决定了 C-3 的步数下界 —— 两者一起涨 ⇒ **数量级不可行**；')
P('  3. 内存上 `nreg=280 @ N=160` 单是 `phi` 就 9.2 GB(f64) ⇒ 加上临时量会超预算。')
P('=' * 100)
