HERE = os.path.dirname(os.path.abspath(__file__))
LED = os.path.join(HERE, 'R30_AUDIT_LEDGER.md')
MARK = '## §147'

SEC = r"""
---

## §147（R261）⚠ **对 `§144` 的措辞更正：`--facet-proj` 是"强压制"而不是"严格归零"**

> 数据：`_r242_p45diff.py` 对 `p45L`/`p45P` 的**更新读数**（step 240）；日志 `_w2_r242b.log`
> 上游：`§144`（"带投影 ⇒ 形态量逐位为零"）

### §147.1 为什么要更正

`§144` 的受控实验用的是 **γ_F3 对比 31.3×**（`ladder 5.0°` vs `perstep 0.05°`），
在那个对比度下带投影时**所有形态列逐位为零**。
⇒ 我当时写成"**`--facet-proj` 让界面能对形态"零影响""。

**但 `_r225` 的 P1-45 对照同样带 `--facet-proj 10`，对比度只有 1.815×，
却随演化**持续分叉**：**

| 读数时刻 | 有差异的列数 | 最大相对差（`dG_near_max`）| `f3_area_m2` |
|---|---|---|---|
| step 160（`§143.5`）| 41 / 95 | 1.250e-01 | 2.547e-02 |
| **step 240（本节）** | **51 / 95** | 1.250e-01 | 2.547e-02 |

**⇒ 带投影时，1.815× 的 γ 变化仍然产生 ~2.5% 的形态差异（且列数随演化**增加**）。**

### §147.2 正确的表述

> **`--facet-proj > 0` **强压制**界面能对形态的影响（在高对比度下可压到"逐位为零"，
> 压制倍数 ≥ 10³），但**不是**对所有对比度都严格归零。**

**⇒ 两条读数并不矛盾**，但 `§144` 的"零影响"**只能限定在高对比度那组实验内**。
**⇒ 判据层面**：`§144` 的 `_r246`/`_r248` 实验**仍然成立**（那是逐位为零的实测）；
**只是不能用它推断"任何对比度下都为零"。**

**⚠ 这也意味着 `§144.3` 的"统一根因"表述要**降一档**：**
投影**不是**把通道彻底关掉，而是**大幅削弱**。
⇒ R165 的 0.03% 否定结果里，**投影是重要因素但不是唯一因素**；
`§142.1` 的"F2 只占 8.7% 面积"与 `§145.2` 的"F3 在 3/4 演化里几乎不存在"**同样是真因素**。
**⇒ `§145.3` 的"三条叠加"归因仍然正确，且现在更站得住。**

### §147.3 ★ 决定性对照（**在跑**）

`_r253`（`p45L0` vs `p45P0`）**与 `_r225` 逐字相同、只把 `--facet-proj 10` 改成 `0`**
⇒ **对比度相同（1.815×）、只差投影** ⇒ 这是把本节的问题**直接量出来**的实验：
* **预言**：`--facet-proj 0` 组的**分叉列数与幅度都应显著大于**投影组的 51 列 / 2.5%。
* 进度：`p45L0`/`p45P0` 各到 step 20（6 个进程竞争 CPU ⇒ 较慢）。

### §147.4 硬规则（补充 ㉕）

**㉕ 的补充**：测"某算子是否切断某通道"时，**必须在**多个对比度**下测**，
否则容易把"高对比度下量不到"误当成"通道被切断"。
⇒ 判据应写成"**压制倍数**"，而不是"**有/无**"。
"""


def main():
    with io.open(LED, 'r', encoding='utf-8') as f:
        txt = f.read()
    n0 = txt.count('\n') + 1
    if MARK in txt:
        print('⚠ 已有 `%s` ⇒ 不重复追加（当前 %d 行）' % (MARK, n0))
        return 0
    # 在 §144 的标题后插更正指针
    anchor = '### §144.2 ★★★ 结果'
    if anchor in txt and '本条已被 `§147` 收窄' not in txt:
        ptr = ('> ⚠⚠ **本条已被 `§147` 收窄**：这里的"形态量逐位为零"是在\n'
               '> **γ 对比 31.3×** 下测的；`_r225` 用 **1.815×** 时带投影仍产生\n'
               '> **~2.5%** 的形态差异（51/95 列）⇒ 正确表述是\n'
               '> **"强压制（≥10³ 倍）"而不是"严格归零"**。\n\n')
        txt = txt.replace(anchor, ptr + anchor, 1)
        print('  ✅ 已在 `§144.2` 处插入收窄指针')
    assert txt.endswith('\n'), '台账末尾不是换行'
    assert '\t' not in SEC, '正文里有制表符'
    txt = txt + SEC
    with io.open(LED, 'w', encoding='utf-8', newline='') as f:
        f.write(txt)
    n1 = txt.count('\n') + 1
    print('✅ 台账：%d 行 → **%d 行**（+%d）；制表符 = %d'
          % (n0, n1, n1 - n0, txt.count('\t')))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
