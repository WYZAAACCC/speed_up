### §18.3 ★★★ 真因（两个环节都有问题）
1. **写入时机**：**检查点在"钉 `P0`"**之前**写**（或写的是钉之前的 `P0`）
   ⇒ **step 20 的检查点里 `f3_pos_p0_m = nan`**，尽管该步 `P0` 已经是 `−2.3157e−06`；
2. **读回**：续跑读到 `nan` ⇒ 等价于"**没存**" ⇒ `P0` **不被恢复**
   ⇒ **在续跑后的第一步（step 40）被重新钉住** ⇒ **基准与一次跑完不同**。

**⇒ ⇒ 于是 `f3_pos_dx = (pm − P0)/dx` 在两臂差 **0.036 Δx**（= 0.0357）—— 与实测**逐数吻合**。**

### §18.4 ★ 为什么"插桩"这一步比"继续读代码"有效（方法上的结论）
* 我先前的两个候选解释**都被实测排除**（守卫、顺序）；
* **插桩一次就给出五条事实**，且**推翻了我从检查点读到的推断**（"A 的 `P0` 是 `nan`"——
  那只是**检查点里**的值，**运行期**的值是 `−2.3179161e−06`）。
**⇒ 教训：**检查点里的值 ≠ 运行期的值**（写入时机可能错开）——
   凡"从落盘文件推断运行期状态"，**必须先用插桩确认两者一致**。**

### §18.5 修法（**两条，都要**）
1. **写入时机**：让 `P0` 的钉基准**发生在**写检查点**之前**（或写检查点时**显式用钉后的值**）；
2. **读回**：`nan` 视为"未设定"（**`:742` 已改**，方向正确）。

