#!/usr/bin/env bash
# _run_dxscan3.sh --- `F-1` 的 **Δx 收敛扫描**（用户 2026-09-28 Round 137 批准的修法①）
#
# 问题（`_w2_terms.log` + `_w2_shape2.log` 实测）
# ---------------------------------------------
#   板条的 `M(n)` 各向异性**没有被形貌表达**：速率比 1 : 0.98 : 0.31（设计 1 : 0.10 : 0.03）。
#   机理已锁定：界面上 `|n·a|>0.9` 的**面积只占 0.7–3.2%** —— **没有"快方向的面"**。
#   `M(n)` 本身经 `M-5` 验证**实现正确**（族内条件均值 `|n·w|`→0.099 vs 设计 0.100 ✓）。
#   ⇒ 剩下唯一要分离的：**这是"网格解析不出晶面"（数值）还是"机制本身不给晶面"（物理）？**
#
# 设计（**单因素：只改 Δx**）
# --------------------------
#   * **物理盒固定** 10.6688 µm（= 64 × 166.7 nm = 128 × 83.35 nm）
#   * **种子固定物理尺寸** `R=500 nm, t=700 nm, elong=1.0, flat_end=False`
#     ⇒ 满足 `R13`（`t/Δx ≥ 3` 且 `R/Δx ≥ 3`）：Δx=166.7 → 4.2/3.0；83.35 → 8.4/6.0；66.68 → 10.5/7.5
#   * **物理时间固定**：`dt = 0.15·Δx/(M·Δf)` ⇒ 步数 ∝ 1/Δx
#       Δx=166.7 → 150 步；Δx=83.35 → 300 步；Δx=66.68 → 375 步
#   * 其余全部默认（`proj2`、`norm_smooth=0`、`β_h=3.5`、`β_w=2.3`、`band_cells=20`）
#
# 判据（**先写死，再看数**）
# ------------------------
#   看 `|n·a|>0.9` 的**面积占比**随 Δx 的走向，以及长窗口 `ΔL:ΔW:ΔT`：
#     * 占比随 Δx 减小**显著上升**（如 2% → 8% → 15%）且速率比同步趋近 1 : 0.1 : 0.03
#       ⇒ **F-1 = 网格限制**（数值）⇒ 修法是分辨率/晶面保真度，不是新物理；
#     * 占比**基本不动**（≈1–3%）
#       ⇒ **F-1 = 机制问题**（各向同性 γ 的 Gibbs–Thompson 把尖端拉圆，
#          与 `windowB_surface.py:240-264` 的 `facet_lam` 记账所指同一个病）⇒ 走 `facet_lam`/新 cusp。
set -u
cd "$(dirname "$0")"

echo "########## Δx 收敛扫描（F-1 判决）  start=$(date -Is) ##########"

bash _run_arm.sh _w2_dx1.log W2-DX1 _probe_shape.py \
    --N 64 --dx-nm 166.7 --steps 150 --every 25 --arms aniso
echo "### DX1 rc=$? @ $(date -Is)"

bash _run_arm.sh _w2_dx2.log W2-DX2 _probe_shape.py \
    --N 128 --dx-nm 83.35 --steps 300 --every 50 --arms aniso
echo "### DX2 rc=$? @ $(date -Is)"

bash _run_arm.sh _w2_dx3.log W2-DX3 _probe_shape.py \
    --N 160 --dx-nm 66.68 --steps 375 --every 75 --arms aniso
