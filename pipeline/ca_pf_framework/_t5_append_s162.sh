## §162 ★★★★★ 第 162 轮：**"带延伸"结论的稳健性检验**（有平台 + 一条诚实的保留）

### §162.1 为什么要做（**阈值是我定的**）
**§149/§150 的结论"step 1000 出现 **8** 个带延伸的场"用了阈值 `fill < 0.10` —— 而那个阈值是**我定的****。
**⇒ 若结论只是阈值的产物，它**不是物理结论**。**⇒ 必须扫阈值。**

### §162.2 实测（`_t5_robust.py`）
```
阈值T     step800   step1000   逐场（step1000）
0.06      0         5          [1,2,3,11,21]
0.08      0         8          [1,2,3,5,11,15,21,24]
0.10      0         8          [1,2,3,5,11,15,21,24]   ← 平台
0.12      2         8          [1,2,3,5,11,15,21,24]   ← 平台
0.14      10        13         …
0.16      21        22         （几乎全部）

step1000 计数序列 = [5, **8, 8, 8**, 13, 22]     ⇒ **8 在 [0.08, 0.12] 上不变 ⇒ 有平台** ✓
step800  计数序列 = [**0, 0, 0**, 2, 10, 21]     ⇒ **在 [0.06, 0.10] 上恒为 0** ✓
```

### §162.3 ★★★ 三条结论（**含一条诚实的保留**）
1. **计数 **8** 在阈值 **0.08–0.12** 上**保持不变** ⇒ **有平台 ⇒ 结论不是阈值产物** ✓；
2. **step 800 在阈值 ≤0.10 时**恒为 0**** ⇒ **"0 → 8 的涌现"在工作阈值上**稳健** ✓；
3. **⚠ 但阈值为 0.12 时 step 800 变成 2（非 0）⇒ 涌现的**起点**对阈值**略敏感****。
   **⇒ 解释**：step 800 有 **2 个场**落在 **0.10–0.12** 区间（**边界场**）；到 step 1000 它们也越过了
   ⇒ **"8 个场从 ≥0.12 降到 <0.10"仍是真实变化**，只是**边界场的归属**随阈值浮动。**

### §162.4 ★ 最终判定（**诚实**）
> **「涌现」这一结论**成立且稳健**（工作阈值下 **0 → 8**，且 **8** 在平台内）；**
> **⚠ 但"**恰好 8 个**"这个数字**有 ±2 的阈值不确定性****
> ⇒ **报告时应写「**约 8 个**（阈值 0.08–0.12 下不变；含 2 个边界场）」**，
>   而不是"8 个"** —— 这是本 goal "数字要么可溯源、要么标明不确定度"的直接执行。

### §162.5 ★ 本轮的意义（**记账**）
**这条检验**不需要等任何东西****（用的是已有快照），**且它验证的是**我自己定的阈值的合理性****。
**⇒ 与 §160 一起，构成对"带延伸"这一整条观测的**双重保障**：**
* **§160**：修掉**跨臂误报**（量具正确性）；
* **§162**：证明**结论对阈值不敏感**（稳健性）。
EOF
