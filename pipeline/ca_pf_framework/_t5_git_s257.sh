## ★★★ 方法论后果：**"最大分量占比"这个指标被 A 与 B 交叉污染**
| 指标 | 受问题 A（stack 建场）影响 | 受问题 B（长宽比退化）影响 | 能否用来判 A |
|---|---|---|---|
| **场号唯一性**（不同场/事件数）| **直接反映** | 无 | **✅ 能**（0.56 → **1.00**）|
| **活跃场数** | **直接反映** | 无 | **✅ 能**（18 → **25**）|
| **最大分量占比** | **间接（板条多 ⇒ 更挤 ⇒ 更低）** | **直接反映** | **❌ 不能** |
| **长宽比 / 长厚比** | 间接 | **直接反映** | **❌ 不能** |

**⇒ 纪律**：**判问题 A 只能用「有效性」与「活跃场数」；判问题 B 只能用「占比」与「长宽比」。**
**不得混用 —— 否则会得出"修复让情况变糟"的错误结论。**

