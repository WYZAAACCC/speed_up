   **长宽比**下降**说明**有一个"变圆/变厚"的机制在起作用**。

### §211.2 ★★★★★ 关键发现：**厚度长得比长度还快**
**场 22 的逐张轨迹：**
```
厚 p3： 0.371 → 0.375 → 0.522 → 0.616 → 0.837    ⇒ **×2.3**
宽 p2： 0.683 → 0.770 → 1.041 → 1.121 → 1.338    ⇒ **×2.0**
```
**⇒ 全场统计：厚度 0.31 → 1.10 µm（**×3.5**）；长度 1.33 → 3.33 µm（×2.5）
   ⇒ **厚度增长快于长度** ⇒ **形状在"变厚" ⇒ 长宽比必然下降**。**

### §211.3 ★★★★ 两条**独立**的原因（**完整答案**）
| # | 原因 | 证据 | 应然值 |
|---|---|---|---|
| **1** | **核不够扁** | 种子实测长宽比 **2.03**；`elong = plate_L/plate_W = **2.0**`（我没传 `--eng-elong`）| 代码写明 **3.75**（`L/W=2400/640`）；**真实板条 5–20** |
| **2** | **生长时厚度**未被抑制**** | 厚度 ×3.5（0.31→1.10 µm），**长宽比 1.90 → 1.49** | **板条厚是**形核属性**，长大中**不变**** |

**⚠ 第 2 条**违反了一条明确的物理**（**就在本仓库文档 §7.5 里**）：**
> **Morito 2005 实测：板条宽在先β晶粒 **2.3→370 µm（160×）**范围内「**does not change**」**
> ⇒ **板条厚是**形核属性**，不是长大属性。**
**⇒ 而我的跑里厚度涨了 **3.5 倍** ⇒ **这条物理没被实现/没被打开**。**

