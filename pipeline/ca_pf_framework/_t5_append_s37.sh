## §37 ★★★★★★ 第 37 轮：`t_wf` 的适用域 —— **两个假设被预登记的正对照否定，真因找到**

### §37.1 正对照 1：**长宽比扫描**（解析长方体 SDF，真值 t = 250 nm）
```
Lb/t     t_wf(nm)   相对差
1.0      375.0      +50.0%     ← 只有立方体这一档不同
1.6      312.5      +25.0%
3.0      312.5      +25.0%
12.0     312.5      +25.0%
20.0     312.5      +25.0%
```
**⇒ 偏差恒为 `t + 1Δx = 312.5 nm`（**+25.0%**），**与长宽比无关**（1.6 → 20 全同）
⇒ **第 36 轮的"侧面污染"假设**被否定** ✓**
（判据**有分辨力**：立方体那一档确实给出不同的 375.0 nm ⇒ 不是"量具恒输出一个数"。）

### §37.2 正对照 2：**带内截断**（检验我自己的离线重建是否引入伪影）
```
(a) 整场光滑 φ            ⇒ 312.5 nm
(b) 带内截断（带外填 1e3） ⇒ 312.5 nm      ← **完全相同**
```
**⇒ 带内截断**不影响**读数 ⇒ **我的离线重建不是伪影来源** ✓**
（这条很重要：否则判据② 的离线路线会被自己的重建方法毁掉。）

### §37.3 ★★★★★ 真因：**种子是**椭球**，不是平板**
启动器 `_t5_short.py` 传的是 **`--nuc-shape ellipsoid`**。
**⇒ 椭球**没有平坦宽面** ⇒ `wide_face_thickness`（为**平坦宽面的板条**设计）
在椭球上量的是**弯曲表面之间的某个距离** ⇒ **数值无物理意义**。
⇒ 这解释了对不上的 +3.95Δx（559.6 vs 312.5），而**不是**量具有 bug、也**不是**我的重建有 bug。

