## §8 ★★★★ 第 65 轮：**门 0/门 4 回归的判据口径**（复核清单第 6 条 —— 必须先钉死）

### §8.1 ⚠ 原判据**在逻辑上不可能成立**（先自我更正）
`§6` 复核清单第 6 条我写的是：
> 「新开关**默认 `linear`**，且已跑**门 0/门 4 回归**验证归档路径逐位不变」

**⇒ 这句话**自相矛盾**：**换入 `lpbf` **就是**改了归档路径** ⇒
    "默认档仍逐位不变"与"已换入"**不可能同时为真** —— 除非**根本没换**。
**⇒ 若不改口径就去测，我必然得到一个**恒 FAIL**的判据，然后可能错误地把"实现"当成"坏了"。**

### §8.2 ★ 正确口径（**拆成三条独立判据**）
| # | 判据 | 怎么测 | 为什么是它 |
|---|---|---|---|
| **6a** | **`--therm-hist linear`（默认档）与换入**之前**逐位相同** | 换入前后各跑同一算例（短跑），比 96 列 | 保证**默认行为不变** ⇒ 归档可复现 |
| **6b** | **`--therm-hist lpbf` 与 `linear` **必须不同**（差异有分辨力）** | 同算例两档对比 | **防止"换了开关但没生效"**（本仓库 P43 的同类：负对照必须有分辨力）|
| **6c** | **`lpbf` 档自身的物理自洽** | `_t5_therm.py` 的两条断言（已 PASS）+ 温度序列落在文献温区 | 保证换入的是**物理正确的**曲线，不是任意曲线 |

**⇒ 三条**各自独立、各自可失败**；**不允许**用一条代替另一条。**

### §8.3 ★ 6b 的具体判据（**预先写死**）
1. **`df`（驱动力）序列必须不同** —— `lpbf` 档的温度会**升到 1923 K**，而 `linear` 档**单调降到 298 K**
   ⇒ 至少在某一步 `|df_lpbf − df_linear| / max|df| > 1e-3`；
2. **`T` 序列必须不同** —— 至少存在一步 `T_lpbf > T_linear + 1 K`
   （**这是"再热"存在的直接证据**；若没有，说明热循环**没生效**）；
3. **`Vt` 末值**应不同（不预设方向 —— 因为"再热会不会促进/抑制转变"**是待研究的物理问题**，
   **不得预先假定**）。

### §8.4 ⚠ 记账：6a 的**前置条件**尚未满足
要做 6a，必须**先把适配层换入引擎**（改成按 `--therm-hist` 分派）。
**⇒ 换入是一行，但换入后 6a/6b/6c 都必须跑过才能起 `lpbf` 臂。**
**⇒ 在 6a/6b/6c 全过之前，`lpbf` 档**不得**用于任何结论。**
EOF
