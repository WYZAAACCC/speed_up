### §223.1 问题（一句话）
**本模型的板条**不够扁**：对照臂的长宽比只有 **1.5–1.9**、长厚比 **3.0–3.9**，
而真实 α′ 板条是 **长宽比 5–20、长厚比 10–50**。**

### §223.2 ★ 根因（**两条独立**，§205–§212 查明）
| # | 根因 | 证据 |
|---|---|---|
| **①** | **核的拉长率只有 2.0**（`elong = plate_L/plate_W = 1000/500`，因为 `--eng-elong` 默认 0 时回退到这个值）| 种子实测长宽比 **2.03**（与 2.0 逐数吻合）|
| **②** | **生长阶段**没有**拉长机制**：`elong` **只进 `seed_plate`**，`advance` 里根本没有它 | §212④（代码逐字）|
| **③** | **厚度没被抑制** ⇒ 长宽比随生长**下降**（1.90 → 1.49）| §211（厚度 ×3.5 > 长度 ×2.5）；**违反 Morito 2005**（板条宽在 160× 晶粒范围内不变）|

### §223.3 ★★★ 解决手段（**剂量-响应实测**，§222）
```
eng-elong   长宽比(step 40)   长厚比(step 40)
0           1.88              3.27      ← 对照
3.75        3.59              6.56
5.00        4.78              8.72
7.00        **6.66**          **12.15**  ← ★ 进入真实区间（5–20 / 10–50）
```
**⇒ 剂量-响应**严格单调**、**尚未饱和**（7 相对 5 仍 +39%）⇒ **`--eng-elong` 是有效手段，且可继续往上试。**
**⚠ 唯一传参即可 —— 不改代码** ✓

