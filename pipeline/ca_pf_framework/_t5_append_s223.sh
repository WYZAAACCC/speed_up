### §223.5 ⚠ 尚未回答的关键问题（**决定 §223.3 能不能用**）
**「step 40 的高长宽比能否**在生长中存活**？」**
* **背景**：`t5H3`/`t5V2` 的**终态**长宽比只有 **1.49 / 1.67**（而它们的**种子期**也不扁）；
* **要看的**：`t5AD_700` 跑满 **1400 步**后的长宽比；
* **判据（预先写死）**：
  * **仍 ≳ 5** ⇒ `--eng-elong` 是**完整解** ✓；
  * **掉到 ~2** ⇒ **生长会把拉长洗掉** ⇒ **必须改物理**（给 `advance` 加拉长项），`eng-elong` 只能部分缓解。

