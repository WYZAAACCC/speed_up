| **圆种子（C，`elong=0`）** | **等轴盒子 ⇒ 长宽比 → **1.0**** |
| **长种子（D，`elong=3.75`）** | **长条盒子 ⇒ 长宽比 → **4.30**** |
**⇒ **所以"核有多扁，它就放大到多扁"** —— 它**不创造**拉长，只是**把已有的拉长"框"出来**。**

