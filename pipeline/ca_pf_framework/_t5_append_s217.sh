* **抹掉**全部块内低角界面**（**F3 面数 1169 → 0**、**块数 6 → 12**）**。
**⇒ ⇒ **D 的 4.30 是"用毁掉块结构换来的"** ⇒ **不是物理，是表示层伪影**（代码自己也说"这是表示层重整，不是新增物理"）。**
**★ 而本轮**独立复现**了 §186**（**用不同的量**：长宽比/长厚比，而不是 F3 面数/块数）。

