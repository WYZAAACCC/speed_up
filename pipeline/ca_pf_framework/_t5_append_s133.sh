| 观察 | 期望（`t5V2`）| 对照（`t5H3` 同期）|
|---|---|---|
| 首个 `fresh` | **成功** | 成功（已见，事件 #25）|
| **`nf2`** | **> 0**（出现异变体界面）| **= 0**（同变体）|
| **`nblk_sig`** | **≥ 2** | **= 1** |
| **`n_var_sig`** | **> 1** | **= 1** |
| `nslab_n1` | 增长 | 24 → 25 |

**⇒ 这是本 goal 对判据 ③(多块)/④/⑥ 的**最后一次、也是最干净的一次检验**：
   两臂除「`m` + `var-rule`」外逐字相同 ⇒ **差异可直接归因**。**
