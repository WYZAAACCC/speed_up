* **⇒ 所以"新块"的条件是"新场 + **不同变体**"，而 `ed` **只能满足前半**；**
* **⇒ `t5V2`（`--var-rule random`）正是为了打破这一点。**

**★ 这也**修正了我 §132 的"待看"**：不是"新块还没出现"，
   而是**在新场**已经**出现的前提下、`ed` 让它**无法成为新块**。**

### §133.4 ★★ 由此得到一条**可判定的预测**（**预先写死**）
