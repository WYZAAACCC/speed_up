#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""_chk_xie_ratio.py --- 用**同试样配对**重算 Xie 2026 的 2D 长:短（纠正我们的非法配对）

背景（Round 141，用户带来的文献汇编抓到）：
`MEASUREMENT_SPEC` 写 Xie 的 2D 长:短 = **16.7–23.8**。核对来源后发现：
    16.7 = 5.065/0.304   ← **最短的长 ÷ 最宽的宽**（跨试样）
    23.8 = 5.685/0.239   ← **最长的长 ÷ 最窄的宽**（跨试样）
⇒ 这正是"**任意配对求极值比**"，是**非法口径**（不是任何一根板条的比值）。
正确做法：**同一试样内**的长 ÷ 宽。

同一估计量对比还有一层：Wang 2026 的 9.0 是「**均值之比**」（8.1/0.9），
不是「单根板条比值的均值」——两个估计量不同，报的时候必须标注。

判据：本脚本输出的「同试样」区间必须**窄于**非法配对区间（数学上必然），
且 ratio-of-means 必须落在同试样均值附近。
"""
import numpy as np

# Xie 2026 正文 Table 2（子代理二次核实：10 行数值 10/10 逐字命中）
TH = np.array([0.2, 0.25, 0.3, 0.4, 0.5, 0.6, 0.7, 0.8, 0.9, 1.0])   # 试样厚度 mm
L = np.array([5.065, 5.109, 5.419, 5.499, 5.471, 5.430, 5.454, 5.539, 5.501, 5.685])
W = np.array([0.239, 0.256, 0.251, 0.262, 0.241, 0.253, 0.262, 0.247, 0.270, 0.304])
assert len(L) == len(W) == 10

print('=' * 96)
print('_chk_xie_ratio —— Xie 2026 Table 2 的 2D 长:短：同试样配对 vs 非法跨试样配对')
print('=' * 96)
print('\n  %-8s %10s %10s %10s' % ('试样(mm)', '长(µm)', '宽(µm)', '同试样 长/宽'))
r = L / W
for i in range(10):
    print('  %-8.2f %10.3f %10.3f %10.2f' % (TH[i], L[i], W[i], r[i]))

print('\n  ① **同试样配对（合法）**     ：%.2f – %.2f   均值 %.2f   中位 %.2f'
      % (r.min(), r.max(), r.mean(), np.median(r)))
print('  ② 均值之比（与 Wang 同估计量）：%.3f / %.3f = %.2f' % (L.mean(), W.mean(), L.mean() / W.mean()))
print('  ③ **非法跨试样配对（我们原先用的）**：')
print('       最短长/最宽宽 = %.3f/%.3f = **%.2f**' % (L.min(), W.max(), L.min() / W.max()))
print('       最最长/最窄宽 = %.3f/%.3f = **%.2f**' % (L.max(), W.min(), L.max() / W.min()))
assert abs(L.min() / W.max() - 16.66) < 0.05 and abs(L.max() / W.min() - 23.79) < 0.05, \
    '与原文档的 16.7/23.8 对不上 ⇒ 来源判断有误，须重查'

print('\n  ⇒ 判定：① 的区间 %.2f–%.2f **窄于** ③ 的 %.2f–%.2f ✓（数学上必然，'
      '但 ③ 不是任何一个观测量）' % (r.min(), r.max(), L.min() / W.max(), L.max() / W.min()))
print('  ⇒ 靶② 的 Xie 端应报 **同试样 %.2f–%.2f（均值 %.2f）**，'
      % (r.min(), r.max(), r.mean()))
print('     并把 16.7–23.8 标注为「**已作废：跨试样非法配对**」。')

# Wang 2026：9.0 是均值之比；另可用 ±SD 给出区间
wl, wl_sd, ww, ww_sd = 8.1, 2.0, 0.9, 0.4
print('\n  Wang 2026（8.1±2.0 / 0.9±0.4 µm）：')
print('       均值之比 = %.2f  （**不是**单根板条比值的均值）' % (wl / ww))
print('       由 ±SD 推的区间 = (8.1−2.0)/(0.9+0.4)=%.2f  到  (8.1+2.0)/(0.9−0.4)=%.2f'
      % ((wl - wl_sd) / (ww + ww_sd), (wl + wl_sd) / (ww - ww_sd)))

lo = min(r.min(), wl / ww)
hi = max(r.max(), (wl + wl_sd) / (ww - ww_sd))
print('\n  ★ 靶②（两篇同篇自洽值的并区间）：**≈ %.0f – %.0f**' % (np.floor(lo), np.ceil(hi)))
print('    （原文档写 9–24；Xie 端 24→%.0f 是因为改用了同试样配对 + 计入 Wang 的 ±SD 上界）'
      % np.ceil(hi))
print('=' * 96)
