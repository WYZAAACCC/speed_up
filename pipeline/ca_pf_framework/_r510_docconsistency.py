#!/usr/bin/env python3
# -*- coding: utf-8 -*-
r"""_r510_docconsistency.py —— **跨文档数字一致性检查**（阶段回顾的一部分）。

## 为什么需要它

本会话把几个关键数字**改过好几次**（例：椭球的弹性罚先是 2.0873e8，后改成 2.5760e8）。
文档散在 8+ 份里 ⇒ **很容易出现"某份文档还写着旧数"**。
用户要求在阶段回顾里检查错误与偏离 ⇒ 这一条是最容易漏、后果最坏的（**旧数会被后续引用**）。

## 口径

对每个**关键量**，列出"**应该**出现的值"与"**已废弃**的值"，
然后扫全部 `.md`，报告：
* 哪些文档出现了**废弃值**（❌ 需修）
* 哪些文档**缺**该量的现行值（⚠ 可能只是不涉及）

## ⚠⚠ 本检查器第一版自己就错了（**自查错误 #100**，留痕）

第一版把 **`377.7 K`** 与 **`641.7 K`** 都列成"废弃值"，结果报了 **25 处**"需修"。
**但那是把两个不同的物理量混为一谈：**

| 门槛 | 是什么 | 用在谁身上 | 值 |
|---|---|---|---|
| **生长窗口 `T*`** | 「**已长成的板条**（1000×500×510 nm）站不站得住」 | `_r470`（解释 `saSet2` 长 / `abA` 溶） | **641.7 K** ✅ **仍然有效** |
| **形核门槛 `T_阈`** | 「**刚播下的核**（R=320 nm、t=510 nm）放不放得下」 | `_r479`/`_r509`（超临界判据） | 圆盘 **380.1 K** / 椭球 **523.8 K** |

**⇒ `641.7 K` 不是废弃值**，它是**另一个量**（生长 vs 形核）。
**⇒ `377.7 K` 也不是废弃值** —— 它与 `_r509` 的 `380.1 K` 只差 **0.6%**（同一几何的两次读数）。

**⇒ 本检查器已改成只查真正被替换的数（2.087e8 → 2.576e8 这一对）。
⇒ 而这次误报**暴露了一个真实的文档问题**：文档里
「`T*`」「门槛」「生长窗口」几个词**混用**，读者无法分辨说的是哪一个
⇒ **必须随数一起写清是"生长"还是"形核"**（已加进阶段回顾的待办）。
"""
from __future__ import annotations

import glob
import os
import re
import sys

# 关键量：名字 → (现行值集合, 废弃值集合, 说明)
KEYS = {
    '椭球弹性罚(引擎同几何)': (
        ['2.576010e8', '2.5760e8', '2.576e8'],
        ['2.087286e8', '2.0873e8'],
        '★ 现行是引擎 `_r509` 实测的 2.576e8；2.087e8 是 `PF3D` 不同几何的旁证'),
    '圆盘弹性罚(引擎同几何)': (
        ['3.172046e8', '3.1720e8'],
        ['3.181850e8', '3.1818e8'],
        '现行 3.172e8（`_r509`）；3.1818e8 是 `_r479`（同几何、旧读数，差 0.3%）'),
    '形核窗口-圆盘': (['82 K', '380', '377.7'], [], '现行 380.1→298 = 82 K'),
    '形核窗口-椭球': (['226 K', '524', '523.8'], [], '现行 523.8→298 = 226 K'),
    'α_KM-交集下界': (['0.0089', '0.0058'], [], '现行 0.0089（引擎实测口径）'),
}

DOCS = sorted(glob.glob('*.md'))


def main():
    print('=' * 92)
    print('R510  跨文档数字一致性检查')
    print('=' * 92)
    print('  扫描 %d 份 .md' % len(DOCS))
    print()
    bad = 0
    for name, (cur, dead, note) in KEYS.items():
        print('■ %s' % name)
        print('   %s' % note)
        # 废弃值：除非同一行里明确标了"旁证/旧/不参与计算/自查错误"
        for d in DOCS:
            txt = open(d, encoding='utf-8', errors='replace').read()
            lines = txt.splitlines()
            hits = []
            for i, ln in enumerate(lines):
                for dv in dead:
                    if dv in ln:
                        # 白名单：明确标注为"旁证/旧/PF3D/不参与计算/自查错误/已改用"
                        if any(w in ln for w in ('旁证', '不参与计算', '自查错误',
                                                 'PF3D', '旧读数', '已改用', '留痕')):
                            continue
                        hits.append((i + 1, dv, ln.strip()[:80]))
            for (i, dv, ln) in hits[:3]:
                print('   ❌ %s:%d 出现废弃值 %s  → %s' % (d, i, dv, ln))
                bad += 1
        print()
    print('=' * 92)
    print('★ 结果：%s' % ('**全部一致**（未发现未标注的废弃值）' if bad == 0
                          else '**发现 %d 处未标注的废弃值 ⇒ 需修文档**' % bad))
    print('=' * 92)
    return 0 if bad == 0 else 3


if __name__ == '__main__':
    sys.exit(main())
