### §111.2 判据（**预先写死**）
| 观察 | 结论 |
|---|---|
| `fresh_covfail` 占多数 | ⇒ **覆盖守卫**在挡（几何条件不足）|
| `fresh_exc` 占多数 | ⇒ `seed_plate` **抛异常**（代码缺陷）|
| `fresh_cand == 0` | ⇒ **根本没有候选**（位点池/落位）|
| `fresh_blocked` 大而 `fresh_cand` 也大 | ⇒ **候选被否**（与 `nfsv_nofield` 同族）|

### §111.3 ⚠ 但**必须先解决一个方法问题**（否则小臂复现不了）
**`fresh` 只在 **`K = n(T_end) = 23` 个事件**才尝试一次** ⇒
**N=96 / 120 步的小臂**可能**连第一个 `K` 周期都到不了**（长跑到 step 701 才出现事件 #24）。
**⇒ 对策（三选一，需实测代价）**：
1. **小臂跑更多步**（如 800 步 ⇒ 内存 ~2 GB × 时长更长；**与长跑并行仍安全**）；
2. **小臂显式传更小的 `--nuc-fresh-every`**（如 5）⇒ **让它更快尝试 `fresh`**
   ⚠ **但这会让小臂与长跑的 `K` 不同 ⇒ 只能回答"`fresh` 为什么被拒"，不能回答"长跑里会不会成功"**；
3. **等长跑自己跑到事件 47/70**（~3 小时）—— **最忠实，但要等**。

**⇒ 我的建议（最保守 + 信息量）：先做 2（快、能拿到**原因**），
   再做 3（忠实、能拿到**系统性**判断）—— 两者回答的是**不同问题**，都要。**

