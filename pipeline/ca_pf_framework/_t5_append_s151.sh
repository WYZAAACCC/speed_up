### §151.3 ★★★ 一条**结构性发现**（**修正我 §145 的误判**）
**`region` **不是**空间连通标签，而是**场/变体标签**** ——
**每个形核场保持自己的 id，**即使与邻居相邻也不合并**。**
**⇒ 这解释了：**
| 观测 | 真因 |
|---|---|
| 我的 `_t5_frag2.py` 报"每场 5 个碎片"（§145）| **一个场的 band **壳层**出现在多处** ⇒ **不是碎片**（我当时归因成"索引映射错"，**其实两者都不对**：`region` 本就不是连通标签）|
| **"距离 0"**（本轮）| **相邻的场** ⇒ 是**真实的场间接触** ✓ |
| `_t5_proj.py` 的包围盒偶尔更大 | 场的胞集**跨到邻居附近** ⇒ 包围盒变大（**口径问题，非测量错**）|

**⚠ 所以 §145/§147 的两轮归因（"我读错数" / "索引映射错"）**都不准确** ——
   真正的答案是**`region` 的语义**：它是**场 id**，不是**连通分量**。
   **⇒ 教训（第 21 条）**：**跨会话的"语义假设"必须回到**产出它的代码**去确认**
   （`region` 由谁写、写的是什么），**不能靠"名字像什么"推断**。**

### §151.4 ★ 对判据④ 的意义（**重要，但仍不构成证据**）
**"早期 7 根板条互相相邻"⇒ 场与场**在几何上已经接触**** ——
**⚠ 但判据④ 要的是**`nf2 > 0`（异变体界面）**，而早期 7 根是**同一变体** ⇒
   **同变体接触 ≠ 异变体接触** ⇒ **仍不构成判据④ 的证据**（§148.4 的记账不变）。**
**⇒ 但它是**判据④ 的前兆**：**同变体先接触（step ~800–1000），异变体接触（`nf2>0`）应在其后** ——
   **⇒ 这可作为**预测**：`nf2` 首次出现的步数应 **> 1000**。**
