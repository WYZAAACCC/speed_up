### §36.3 ★ 最可能的原因（**量具的适用域**）
step 0 的种子是**扁平板**：`plate_L 1000 × plate_W 500 × 厚 312.5 nm`
⇒ 平面内长宽比只有 **~3.2 : 1.6 : 1**（**接近方形**）。
`wide_face_thickness` 的宽面判据是 `(n·n*)² > cos2_min = 0.81`（⇒ 25° 以内）
⇒ **在这种方形板上，侧面与宽面的法向夹角可能落在 25° 内 ⇒ 侧面被误判为宽面**
⇒ **"两宽面之间的距离"被污染 ⇒ 读数偏大 ✓ 与观测一致**

**⇒ ★★ 结论：该量具是为**长条形板条**设计的；在**方形种子/方块**上**不是有效厚度**。
**⇒ 判据② 用 `t_wf` 前，**必须先过一条适用性判据**（例如：平面内长宽比 ≥ 某阈值）。**

### §36.4 判据② 的**修正后**口径（**在适用性判据定出来之前**）
