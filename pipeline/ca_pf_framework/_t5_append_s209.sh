## §209 ★★★★★★★ 第 209 轮：**用户问"问题是什么 / 为什么没量长宽比"** —— 如实作答

### §209.1 问题是什么（**一句话**）
> **模型里"新形核的板条"是**圆盘**，不是**长条板**
> ⇒ **这个结构不是由板条组成的，而是由"团块"组成的。**

**链条：**
```
--eng-elong 默认 0.0（我从不传它）
  ⇒ 引擎形核用"圆盘"（各向同性）
  ⇒ 圆盘长大时各方向一样快 ⇒ 长成"更大的团"
  ⇒ 实测：长厚比 3.43（种子）→ 3.02（长大 7 倍后）—— **几乎没变**
  ⇒ 真实 α′ 板条：长宽比 5–20、长厚比 10–50
```
**⇒ 后果**：**判据② 的"长宽比符合物理"不成立**；
**且判据③（堆叠成块 + 块内低角晶界）也受影响** ——
**引擎自己警告：「足迹只有长条板的 1/5、F3 面积会小 ~7 倍」** ⇒ **块内界面可能少一个量级**。

### §209.2 ★★★★★ 为什么过程中没量长宽比（**诚实**）
**先纠正：我**量了**，还报了数（长宽比 2.9–5.4，写了"达标"）。
⇒ **问题不是"没量"，而是**量错了四层**：**

| # | 我做的 | 错在哪 |
|---|---|---|
| **1** | **量**沿 `a_ax` 的包围盒跨度**当"长度"** | **`a_ax` 不是板条长轴** —— 长轴须用 PCA 或沿板条自身方向 |
| **2** | **只在 step 200/400/1000 量** | **那时还**没开始长**（生长在 **step 1360–1800**）⇒ 测到的是**种子尺寸**，还当成"板条长度" |
| **3** | **没有**跨时间追同一根**** | **"生长"= 同一根随时间的尺寸变化**；我只量**静态尺寸** ⇒ **结构上就量不到"生长"** |
| **4** | **没给这个量具做正对照** | **PCA/包围盒都是"最优化"类量** ⇒ 按本 goal 硬要求（"凡最优化得到的量必须先用解析已知答案验证最小化器本身"）**本该先验** —— 我给厚度量具（`t_wf`）做了 **13 个**解析对照，**却没给形状量具做**，**直到用户让我查** |

### §209.3 ★★★ 最根本的原因（**前四条都是表象**）
> **我拿"量出来的数落在文献范围里"当成了"物理正确"，
>   却从没问过一句：「**什么决定板条长度？**」**

**⇒ 只要问了，立刻会撞到 `plate_L` / `plate_W` / `--eng-elong` 三个参数 —— 而**根因就在那里**。**
**⚠ 而且**引擎自己在启动横幅里就打了警告**（「核形状：**圆盘**……足迹只有长条板的 1/5」），
**它一直在 `_w2_t5_short_t5H3.log` 的第 2585 行，我从没读过那一行。****
**★ 真正抓住它的是**用户**（"板条长绝对不可能是 1.2 微米"）——
   我的"文献范围对照"没有用户的物理直觉可靠，因为我对照的是**记忆里的数字**，
   而不是**从机制推出来的期望值**。**

### §209.4 ★ 纪律（**第 25 条 —— 这次的根教训**）
> **第 25 条**：**报任何"几何/形貌"量之前，必须先回答「**它由什么决定**」** ——
> **并把这个"决定它的机制"（参数/公式/代码位置）写进报告。**
> **判据**：**若我说不出"这个数由哪几行代码/哪几个参数决定"，
>   那么"它落在文献范围内"**不构成**物理正确的证据** —— 那只说明它**没离谱**，不说明**它对**。
> **⚠ 配套（第 26 条）**：**凡是**自造的**几何量具（形状/长度/取向），
>   **必须先做**解析形状**的正对照（合成椭球/长方体），再做**已知配置**的对照（如种子 = `plate_L/W/T`）。**
>   **本轮的两次对照正是这么做才抓到问题的**（§208：合成对照暴露了离散极限，种子对照证明了数据链）。**
