## 三条结论
1. **判据② 应报"**部分达标**"**：**57% 的场是合格板条**（长宽比 5.1-9.1、长厚比 11-14，
   长 3.5-4.5 µm / 宽 0.47-0.68 µm / 厚 0.31 µm）；**43% 是等轴团块**（长宽厚相近）。
   **=> 我先前只报中位（6.24）是**不完整的** —— 中位被那 8 个板条"代表"了，掩盖了 43% 的团块。**
   **（第 29 条纪律要防的正是这个：中位达标 ≠ 每根达标。）**
2. **团块的体素很大（1522-4948）** => **它们是**长大之后**才变团的**（种子只有 577 体素）
   => 与 `t5AD_1000`（长宽比 7.32 → 1.24）**同一机制**（**长程变团**）。
3. **长厚比（中位 11.48）比长宽比（中位 5.25）更"好"** => **厚度方向钉扎良好**（0.31 µm 很稳）；
   **问题出在**面内**：团块在面内两个方向都长到 4-6 µm** => **面内各向异性没能拉住它们。**
   ⚠ 这与 §234 的结论（面内已有 ~10:1 各向异性）**矛盾** => **值得后续单独查，但现在不下结论。**

