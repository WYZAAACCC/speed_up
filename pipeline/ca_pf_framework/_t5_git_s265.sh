### 5.3 burst 修复（**用户明确要求**）
```
★ 现状：`n(T) = floor(α_KM·(M_s − T))` ⇒ **与 ΔT 线性** ⇒ **每档恒定 3 个核**
   ⇒ **没有 burst**（真实 athermal 马氏体是 **Ms 附近爆发 + 随后饱和**）。
★ 物理正确的形式：**KM 的分数律** `f(T) = 1 − exp(−α(M_s − T))`
