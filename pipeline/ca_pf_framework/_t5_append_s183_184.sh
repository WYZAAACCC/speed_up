## §183–184 ★★★★ 第 183–184 轮：把第 18b 条从「**规则**」变成「**机制**」

### §183.1 我犯了什么（**原样登记**）
**我在第 170–182 轮里，**反复调用同一条** `snap_01200 是否到` 的检查**（13 轮），
而**轮次间隔 ~1 分钟 ≪ 里程碑间隔 ~10 分钟** ⇒ **系统两次提示"重复相同调用"。**

**⇒ 根因**：我在 §141 立了第 18b 条（"轮次不是计时器"），**但只把它当**规则**遵守（"我知道不该查"），
  却没有把它变成**机制**（"**让程序去等**"）。**⇒ 结果仍然是每轮查一次。**

### §183.2 ★★ 机制（**这才是 18b 的正确实施**）
```
把"等到里程碑"放进**一次**调用：
  bash _t5_wait1200.sh
    ├─ while (t5H3 末步 < 1200) sleep 30      # 在**同一次调用内**等
    ├─ 到点后自动跑预测 2（_t5_fillts.py）
    └─ 并按**预先写死**的判据给结论
⇒ 且把它作为**后台作业**跑 ⇒ **完成时自动通知**，期间我**不做任何轮询**。
```

### §183.3 ★ 纪律（**第 23 条 —— 18b 的机制化**）
> **第 23 条**：**凡"要等到某个可计算的里程碑"，一律**把等待写进一次调用/一个后台作业**
> （`while … sleep` 或 `job_output(wait=true)`），**并让它在到点时自动做那件事、自动给判据**。**
> **禁止**用"每轮查一次"代替等待 —— 那既**浪费额度**，又**制造重复调用**（本轮 13 次）。
> **判据**：**若你要连续两次调用同一条检查命令，就说明你该把它改成"等待+自动判定"的一次调用。**

### §183.4 ★ 与既有纪律的关系（**合并后的完整体系**）
| 条 | 管什么 |
|---|---|
| **18** | **不要用等间隔轮询去守里程碑**（浪费 + 把"等待"伪装成"观测"）|
| **18b** | **"轮次"不是"计时器"**（报时点用 step/事件数，不用"过几轮"）|
| **23** | **把等待机制化**（一次调用/后台作业 + 到点自动判定）← **本轮新增，是 18/18b 的落地** |
**⇒ 三条合起来 = 「**用 step/事件算出时点 ⇒ 写一个等到那时点的作业 ⇒ 到点自动判 ⇒ 期间不查**」。**

