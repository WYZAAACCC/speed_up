### §167.3 ★★ 但对**判据⑤(B) 覆盖**要**降低预期**（**诚实**）
**要达到 ≥6/8 子区覆盖，需要 `fresh` 位点散布在 ≥6 个子区** ——
**而 `fresh` 只有 **~5–6 次** ⇒ **覆盖 ≥6/8 是**临界**的**（最好情况刚好够，最坏情况不够）。**
**⇒ 所以：**
| 判据 | 在 `t5V2` 上的**现实预期** |
|---|---|
| **④ 块间影响** | **较可能达成**（只要出现 ≥2 个块，且它们最终相遇）|
| **⑤(B) 覆盖 ≥6/8** | **⚠ 临界**（5–6 个 `fresh` 位点恰好勉强）|
| **⑥ 多变体** | **较可能达成**（`random` 每次抽不同变体）|

### §167.4 ★ 若 ⑤(B) 也临界，则**修法方向**（**记账，不擅自实施**）
**提升 `fresh` 频率**（如 `--nuc-fresh-every` 显式调小）**会与 `--nuc-block-target` 不自洽**
（§122 实测：引擎 N8 会**拒绝运行**）。
**⇒ ⇒ 真正的可调量是 **`--nuc-block-target B`（块数目标）**：**
**`实际块数 = ceil(B·n/K)` 必须等于 `B` ⇒ 取 `K = n(T_end) = 23` 时**恒等**；
**⇒ 要更多块 ⇒ 只能**提高 `B`****，而 **`B` 受 `nv ≥ B·n` 限制**（`nv=72` ⇒ `B ≤ 3`）。**
**⇒ ⇒ 所以「更多 `fresh`」在本机内存下**已经到顶**（`B=3`、`nv=72`）——**
   **这与 §164 的"填充被 `nv` 线性限制"是**同一个根源**。**

**⇒ ★ 最终诚实结论（**供用户判断**）：**
> **在「盒 ≥10 µm」+「本机 22 GB」两条硬约束下，`nv = 72` 已是上限**
> **⇒ 块数目标 `B = 3`、板条上限 69 根、填充上限 1.76%、`fresh` 次数 ~5–6 都是**同一约束的推论**。**
> **⇒ 判据 ⑤ 的 (A) 读法**不可能**；**(B) 读法**临界可达**；④⑥ **较可能可达**。**
