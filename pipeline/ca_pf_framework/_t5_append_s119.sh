## §119 ★★★★ 第 119 轮：基于封顶结论的**推荐配置**（**需用户决定**，长跑不动）

### §119.1 问题回顾（§117/§118 已逐字验证）
* **`t5H3` 的 `nslab_n` 停在 `m = 24`** ⇒ 拒绝消息逐字为"**无可用空场/落位失败**"；
* **⇒ 单变体组的**表示上限**已用尽** ⇒ **不会再有新块**；
* **⇒ 判据 ③(多块)/④/⑥ 在本配置下**不可能达成**（**不是步数问题**）。

### §119.2 ★★ 两个**必须同时解决**的因素（**这是关键洞察**）
| # | 因素 | 现状 | 为什么 |
|---|---|---|---|
| **1** | **每变体组的场数 `m`** | **24**（已用尽）| **新块需要空位；用尽后无位可放** |
| **2** | **`fresh` 选哪个变体** | **`--var-rule ed` ⇒ 永远 `argmax(drv)`** | **即使有空位，若总选**同一变体** ⇒ 仍无新块（`fresh` 需要**不同变体**的空场）** |

**⇒ ⇒ 只改 1 或只改 2 都**不够**（我先前 §89–§92 的几轮就是因为只盯一个而反复被推翻）。**

### §119.3 ★ 推荐配置（**同时改 1 和 2**，且**内存不变**）
```
--nvar 2 --m 36 --var-rule random --nuc-fresh-every 5
         ↑        ↑                    ↑
         |        |                    └─ 让 fresh 更频繁地尝试（K=5 而非 23）
         |        └─ 随机选变体 ⇒ 可能出现"不同变体"的 fresh ⇒ 新块
         └─ 每组 36 个场 ≥ 24（留余量）;  nv = 2×36 = 72（**与 t5H3 相同 ⇒ 内存不变**）
```
| 项 | 值 | 理由 |
|---|---|---|
| `nv` | **72** | **与 `t5H3` 相同 ⇒ 内存 ~6 GB ⇒ 与长跑并行后合计 ~12 GB < 22 GB** ✓ |
| `nvar` | 2 | **保留多变体的可能**（`ed` 下只有 1 个变体会被选中）|
| `m` | 36 | ≥ 24（旧上限）+ 余量 |
| `--var-rule` | **random** | **`fresh` 出现"不同变体"的唯一途径**（§91 读代码得出；§92 补充：**只对 `fresh` 生效**）|
| `--nuc-fresh-every` | **5** | 默认自动取 `K = n(T_end) = 23` ⇒ **太稀**（长跑 800 步才 1 次尝试）⇒ 显式调密 |

**⚠ 三项记账**：
1. **`--var-rule random` 是**显式的物理选择****（代码注明 `ed` 默认下逐位不变 ⇒ 换它是改物理，须记账）；
2. **`--nuc-fresh-every 5` 改的是"新块的调度频率"** ⇒ **与 abA 的 `K = 23` 不同** ⇒ **该臂与 abA 的"块数"不可直接比**；
3. **本方案**不保证**成功** —— 它只是**同时解除了两个已识别的障碍**；**判据（预先写死）**：
   * **`n_var_sig` 必须 > 1**（否则"随机选变体"没生效）；
   * **`nblk_sig` 必须 ≥ 2**（否则仍无新块）；
   * **`nf2 > 0`**（块相遇的签名）。

### §119.4 ★ 处置（**按"最保守 + 可回退 + 显式记账"**）
| 选项 | 内容 | 判定 |
|---|---|---|
| **A** | **保持 `t5H3` 继续跑**（它仍在产出 ①②③⑤ 的数据）| **采用**（不损失任何东西）|
| **B** | **另起一臂**（§119.3 的配置）| **⚠ 需用户确认** —— 它**改物理配平**（`var-rule`/`fresh-every`），<br>而用户逐字要求"参照 abA"⇒ **偏离 abA 的算例应当先问** |
| **C** | 等 `t5H3` 跑完再说 | 时间最长（1–2 天）|

**⇒ 我的处置**：**A（采用）+ 把 B 作为明确建议提交给用户**（因为它涉及"改物理机制"，属用户该拍板的事）。
**⚠ 若用户希望我直接起 B，请明确说一声 —— 我不擅自改物理配平。**
