#!/usr/bin/env bash
# _run_facet.sh --- `facet_lam` 单因素扫描（`F-1` 的**下一个候选修法**）
#
# 为什么是它（`WINDOWB_ROADMAP_TO_CORRECT.md §9.20b` 的排序第 1 条）
# -----------------------------------------------------------------
# `F-1` 的最终判决：**不是分辨率限制**（打开 `elastic_soft` 后 Δx=166.7 与 83.35 给出
# **完全相同**的 ΔL/ΔW = 3.16），而是**实际被施加的各向异性只有设计值的 50–70%**
# （反解 β_w^eff = 1.15 vs 设计 2.3；β_h^eff = 2.44 vs 3.5），且与网格无关。
# 机理：界面法向取自 **跨 2 胞的中心差分**，`|∇φ|` 实测 0.73–0.94 ⇒ **法向含 30–45° 角散布**
# ⇒ `M(n)` 的指数被 ⟨cos²⟩ 缩放。
# ⇒ 既然加密无用，就要**从"能量侧"独立地钉住晶面** —— 这正是
#   `windowB_surface.py:240-264` 的 `herring_stiffness_cusp`（经 `facet_lam` 施加）
#   **早已实现、但从未被任何算例调用过**。
#
# 解析预期（γ0=0.15、aniso=0.4、ε_c=0.05）
# ----------------------------------------
#   默认（aniso 分支）：宽面 γ_eff = γ0(1+2Λ) = **0.27**；尖端/侧面 γ0(1−Λ) = **0.09**  ⇒ 对比 **3×**
#   Λ=0.4（尖点分支）：宽面 ≈ γ0Λ/ε_c = **1.34**；尖端/侧面 = **0.15**                ⇒ 对比 **8.9×**
# ⇒ **宽面被硬化 ×5，尖端只 ×1.67** ⇒ 预期"板条更平"（T 长得更慢）。
# ⚠ 代码是 `elif` ⇒ `facet_lam>0` 会**取代** aniso 分支（不是叠加）。
# ⚠ `facet_lam` **只区分 `n*` 与"其余"**，不区分 `a` 与 `w`
#   ⇒ 它**预期改善 `L/T` 与 `W/T`，但不直接改善 `L/W`**。这一点必须如实报。
#
# 判据（先写死）
# --------------
#   * 若某档使 `ΔL/ΔT` 或 `ΔW/ΔT` **明显上升**且 `fill_n` 上升 ⇒ 尖点有效 ⇒ 再上长跑；
#   * 若各档 `ΔL:ΔW:ΔT` **逐位相同** ⇒ **又是一个死开关**（`F-3`），必须查代码而不是调参；
#   * 若变差 ⇒ 记录并关闭该方向。
set -u
cd "$(dirname "$0")"

for LAM in 0.0 0.2 0.4 0.8; do
    echo "########## facet_lam = ${LAM}  start=$(date -Is) ##########"
    bash _run_arm.sh "_w2_facet_${LAM}.log" "W2-FACET${LAM}" _probe_shape.py \
        --N 64 --dx-nm 166.7 --steps 150 --every 25 --arms aniso --facet-lam "${LAM}"
    echo "### FACET ${LAM} rc=$? @ $(date -Is)"
done

echo "########## facet 扫描结束 end=$(date -Is) ##########"
