| **D** | **换机器/提内存到 ~48 GB** | ⚠ 环境变更，**须用户决定** |
**⇒ **我的建议：把 A 作为当前结论，把 D 作为明确建议提交**（**这是"改环境"，属用户该拍板的事**）。**

