| **该代理的**能**与**不能**** | **能**：证明"多变体**机制**通了"（`random` 确实选出了第 2 个变体）✓<br>**不能**：证明"**自协调**"——**自协调要求这些变体的**形状应变互相抵消****（需**特定变体组合**，不是任意 2 个）|
| **正确的表述** | **「判据⑥ 的**前提机制**已通（多变体可发生 + 块数在增），但**自协调本身未验证**」** |
| **⚠ 更根本** | **2–3 个变体**原理上不足以谈自协调**（Ti64 有 **12** 个）|

### §205.4 ★★★ 统一的图景（**四条判据的瓶颈是**同一个****）
**在「盒 ≥10 µm」+「本机 22 GB」两条硬约束下：**
```
nv = 72（上限）
├─ 变体数 nvar ≤ 3          （§205：自协调需 12 ⇒ ❌ 原理上做不到）
├─ 块数     B ≤ 3           （§167）
