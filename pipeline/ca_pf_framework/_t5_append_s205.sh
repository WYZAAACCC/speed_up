**⇒ 我先前把判据④（块间相互作用）与⑥（自协调）当成**两个独立判据**，这是**机械的** ——
   **物理上：自协调**就是**多变体之间互相 accommodate（形状应变互相抵消）** ⇒ **④ 是⑥ 的**机制****。**

### §205.2 ★★★★ 结构性约束（**纯算术，可复核**）
**模型的场预算**：`nv = nvar × m`
* **约束 1（总场数）**：`nv ≥ B·n(T_end) = B × 23`；
* **约束 2（每组容量）**：`m ≥ 该组板条数`（**单变体结构时该组要装下全部 23 根**）；
* **⇒ ⇒ `nvar ≤ nv / 23`。**

| `nv` | 内存（0.16 GB/场）| **`nvar` 上限** | 能容纳 Ti64 的 **12** 个 Burgers 变体？ |
|---|---|---|---|
| **72（本机现配）** | **11.5 GB** ✅ | **3**（72/23）| **❌ 差 4 倍** |
| 137（22 GB 上限）| 21.9 GB ✅ | **5** | ❌ |
| **276**（12 变体所需）| **44 GB** | **12** | ✅ **但内存 ❌ 超本机 2 倍** |

**⇒ ⇒ 两条硬结论：**
1. **本机内存内（`nv ≤ ~137`）⇒ `nvar` 上限 = **5**；**现配 `nv=72` ⇒ 上限 **3****；
2. **要真容纳 Ti-6Al-4V 的 **12 个变体**，需 `nv ≥ 12 × 23 = **276**` ⇒ **内存 ≈ 44 GB**** ⇒
   **远超本机 22 GB**（**P23**）。**

