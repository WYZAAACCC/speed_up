```
**⇒ **这五条全是**同一个 `nv` 约束的推论**** —— 而**自协调需要 12 个变体 ⇒ 需 `nv ≈ 276` ⇒ 44 GB**。

### §205.5 ★ 诚实的处置（**按自主规则：不擅自改物理配平，如实报告**）
| 选项 | 内容 | 代价/风险 |
