### §165.1 张力（§164 发现）
**「填满整个盒子」有两种读法：**
| 读法 | 要求 | 代价 |
|---|---|---|
| **(A) 高体积分数**（字面）| 达 abA 的 11.8% ⇒ **~460 根板条** | **`nv ≳ 460` ⇒ 内存 ~74 GB** |
| **(B) 结构的**影响范围**铺满盒子** | 随机位点撒遍全盒 + 各处都长起来 | **当前 `nv=72` 已可检验** |

### §165.2 ★★★★ **决定性论证：用户自己的约束排除了 (A)**
**用户逐字要求（两条**同时**成立）：**
1. **「计算盒 ≥10 µm（装得下板条）」**
2. **「本机内存与可接受用时之内」**

**⇒ 而 (A) 需要 `nv ≳ 460`：**
* **N=160 下约 0.16 GB/场 ⇒ `460 × 0.16 ≈ 74 GB`**（**P23：本机可用 22 GB**）；
* **⇒ **(A) 与要求 2 **直接冲突**；**
* **⇒ 而缩小盒子可以降内存，但与要求 1（盒 ≥10 µm）**直接冲突**。**

**⇒ ⇒ **所以 (A) 在用户的约束集下**无解** ⇒ 自洽的读法只能是 **(B)**** ——
**这不是我的偏好，是**约束的必然推论**。**

### §165.3 ★ 决策（**按自主规则：最保守 + 可回退 + 显式记账**）
| 项 | 内容 |
|---|---|
| **采用** | **⑤ 的合格线 = (B)：结构的**影响范围**铺满盒子**（随机形核位点撒遍全盒 + 各处的块都长起来），**而非高体积分数** |
| **可回退** | ✅ **不删任何数据、不改任何代码** ⇒ 若用户澄清为 (A)，**同一批数据仍可重判**（填充率已记录）|
| **记账** | **①** 本读法**不是**"降低标准以让它通过"——**它是用户约束的唯一自洽解**；<br>**②** 若用户要求 (A)，则**必须同时放宽内存或盒尺寸**（**需要用户指示**）；<br>**③** 无论哪种读法，**当前填充 1.08%（理论上限 1.76%）这一事实照常报告，不掩饰** |

